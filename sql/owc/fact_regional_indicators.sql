WITH ACS_DATA AS (
    SELECT 
        AREAID, 
        AREAID_NAME, 
        MEDIAN_HOUSEHOLD_INCOME, 
        POVERTY_LEVEL_PCT 
    FROM 
        LIGHTCAST.TULSA_FOR_YOU.DAT_ACS_INDICATORS
    WHERE
        AREAID_TYPE = 'COUNTY'
),
-- Retrieve Labor Force Participation Rate, Unemployment Rate and Number Employed for Current Year
CURR_YEAR AS (
    SELECT
        AREAID,
        AREAID_NAME,
        LFP_DENOM,
        AVG((EMP + UNEMP) / POP) AS LFPR, -- LFP_DENOM / POP (GABE CHANGED)
        ROUND(AVG(UNEMP),0) AS UNEMP,
        AVG(UNEMP / (EMP + UNEMP)) AS UNEMPR, -- UNEMP / LFP_DENOM (GABE CHANGED)
        ROUND(AVG(EMP),0) AS EMP

    FROM LIGHTCAST.TULSA_FOR_YOU.DAT_LABOR_FORCE
    WHERE
        AREAID_TYPE = 'COUNTY'
        AND YEAR = 2025
        -- AND MONTH = MONTH(CURRENT_DATE()) - 3 (GABE CHANGED by COMMENTING LINE)
    GROUP BY
        AREAID,
        AREAID_NAME,
        LFP_DENOM
),

-- Retrieve Labor Force Participation Rate, Unemployment Rate and Number Employed for Previous Year
PRIOR_YEAR AS (
    SELECT
        AREAID,
        AREAID_NAME,
        LFP_DENOM,
        AVG((EMP + UNEMP) / POP) AS LFPR, -- LFP_DENOM / POP (GABE CHANGED)
        ROUND(AVG(UNEMP),0) AS UNEMP,
        AVG(UNEMP / (EMP + UNEMP)) AS UNEMPR, -- UNEMP / LFP_DENOM (GABE CHANGED)
        ROUND(AVG(EMP),0) AS EMP
    FROM LIGHTCAST.TULSA_FOR_YOU.DAT_LABOR_FORCE
    WHERE
        AREAID_TYPE = 'COUNTY'
        AND YEAR = 2024
        -- AND MONTH = MONTH(CURRENT_DATE()) - 3 (GABE CHANGED by COMMENTING LINE)
    GROUP BY
        AREAID,
        AREAID_NAME,
        LFP_DENOM
),
-- Retrieve Population for Current Year
CURR_YEAR_POP AS (
    SELECT
        YEAR,
        AREAID,
        AREAID_NAME,
        ROUND(SUM(POP),0) AS POPULATION
    FROM
        LIGHTCAST.TULSA_FOR_YOU.DAT_DEMOG
    WHERE
        AGEID LIKE 'G%'
        AND RACEID = 0
        AND GENDERID = 0
        AND AREAID_TYPE = 'COUNTY'
        AND YEAR = 2024 -- GABE CHANGED
    GROUP BY
        YEAR,
        AREAID,
        AREAID_NAME
),

-- Retrieve Population for Previous Year
PRIOR_YEAR_POP AS (
