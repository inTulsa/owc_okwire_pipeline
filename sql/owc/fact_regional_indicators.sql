    WHERE
        AGEID LIKE 'G%'
        AND RACEID = 0
        AND GENDERID = 0
        AND AREAID_TYPE = 'COUNTY'
        AND YEAR = 2023 -- GABE CHANGED
    GROUP BY
        YEAR,
        AREAID,
        AREAID_NAME
),

-- Retrieve Number of Job Postings for Current Year
CURR_JOB_POSTINGS AS (
    SELECT
        YEAR(POSTED) AS YEAR,
        COUNTY AS AREAID,
        COUNTY_NAME AS AREAID_NAME,
        COUNT(*) AS NUM_POSTINGS
    FROM 
        LIGHTCAST.TULSA_FOR_YOU.POSTINGS
    WHERE
        YEAR(POSTED) = YEAR(CURRENT_DATE())
    GROUP BY 
        YEAR,
        AREAID,
        AREAID_NAME
),

-- Retrieve Number of Job Postings for Prior Year
PRIOR_JOB_POSTINGS AS (
    SELECT
        YEAR(POSTED) AS YEAR,
        COUNTY AS AREAID,
        COUNTY_NAME AS AREAID_NAME,
        COUNT(*) AS NUM_POSTINGS
    FROM 
        LIGHTCAST.TULSA_FOR_YOU.POSTINGS
    WHERE
        YEAR(POSTED) = YEAR(CURRENT_DATE())
    GROUP BY 
        YEAR,
        AREAID,
        AREAID_NAME
),

-- Retrieve Number of Job Postings for Last 365 days
CURR_ROLLING_JOB_POSTINGS AS (
    SELECT
        COUNTY AS AREAID,
        COUNTY_NAME AS AREAID_NAME,
        COUNT(*) AS NUM_POSTINGS
    FROM 
        LIGHTCAST.TULSA_FOR_YOU.POSTINGS
    WHERE
        DATEDIFF(YEAR, POSTED::DATE, CURRENT_DATE()) < 1
    GROUP BY 
        AREAID,
        AREAID_NAME
),

-- Retrieve Number of Job Postings for Prior 365 day period
PRIOR_ROLLING_JOB_POSTINGS AS (
    SELECT
        COUNTY AS AREAID,
        COUNTY_NAME AS AREAID_NAME,
        COUNT(*) AS NUM_POSTINGS
    FROM 
        LIGHTCAST.TULSA_FOR_YOU.POSTINGS
    WHERE
        DATEDIFF(YEAR, POSTED::DATE, CURRENT_DATE()) >= 1
        AND DATEDIFF(YEAR, POSTED::DATE, CURRENT_DATE()) < 2
    GROUP BY 
        AREAID,
        AREAID_NAME
),

-- Retrieve Number of Enrollment for most recent year
