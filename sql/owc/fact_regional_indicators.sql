SELECT
    CURR_YEAR.AREAID AS AREAID,
    CURR_YEAR.AREAID_NAME AS COUNTY_NAME,
    CURR_YEAR.EMP + CURR_YEAR.UNEMP AS CURRENT_YEAR_LABOR_FORCE, -- FF.1.1 (GABE CHANGED)
    PRIOR_YEAR.EMP + PRIOR_YEAR.UNEMP AS PRIOR_YEAR_LABOR_FORCE, -- (GABE CHANGED)
    CURR_YEAR.LFPR AS CURRENT_LABOR_FORCE_PARTICIPATION_RATE, -- FF.1.2
    PRIOR_YEAR.LFPR AS PRIOR_LABOR_FORCE_PARTICIPATION_RATE,
    CURRENT_YEAR_LABOR_FORCE - PRIOR_YEAR_LABOR_FORCE AS RAW_CHANGE_IN_LABOR_FORCE, -- FF.1.3
    (CURRENT_YEAR_LABOR_FORCE - PRIOR_YEAR_LABOR_FORCE) / PRIOR_YEAR_LABOR_FORCE AS PCT_CHANGE_IN_LABOR_FORCE,-- FF.1.3
    CURR_YEAR.UNEMP AS CURRENT_UNEMPLOYED, -- FF.2.1
    PRIOR_YEAR.UNEMP AS PRIOR_UNEMPLOYED,
    CURR_YEAR.UNEMPR AS CURRENT_UNEMPLOYMENT_RATE, -- FF.2.2
    PRIOR_YEAR.UNEMPR AS PRIOR_UNEMPLOYMENT_RATE,
    (CURRENT_UNEMPLOYMENT_RATE - PRIOR_UNEMPLOYMENT_RATE) / (PRIOR_UNEMPLOYMENT_RATE) AS PCT_CHANGE_IN_UNEMPLOYMENT_RATE, -- FF.2.3
    CURR_YEAR.EMP AS CURRENT_EMPLOYED, -- FF.3.1
    PRIOR_YEAR.EMP AS PRIOR_EMPLOYED, 
    CURRENT_EMPLOYED - PRIOR_EMPLOYED AS CHANGE_IN_EMPLOYED, -- FF.3.2
    CURR_YEAR_POP.POPULATION AS CURRENT_POPULATION, -- FF.4.1
    PRIOR_YEAR_POP.POPULATION AS PRIOR_POPULATION,
    CURRENT_POPULATION - PRIOR_POPULATION AS RAW_CHANGE_IN_POPULATION, -- FF.4.2
    (CURRENT_POPULATION - PRIOR_POPULATION) / PRIOR_POPULATION AS PCT_CHANGE_IN_POPULATION, -- FF.4.2
    ACS_DATA.MEDIAN_HOUSEHOLD_INCOME AS MEDIAN_HOUSEHOLD_INCOME, -- FF.5.1
    CURR_JOB_POSTINGS.NUM_POSTINGS AS CURRENT_NUMBER_POSTINGS, -- FF.6.1
    CURR_ROLLING_JOB_POSTINGS.NUM_POSTINGS AS CURRENT_ROLLING_NUMBER_POSTINGS,
    PRIOR_ROLLING_JOB_POSTINGS.NUM_POSTINGS AS PRIOR_ROLLING_NUMBER_POSTINGS,
    (CURRENT_ROLLING_NUMBER_POSTINGS - PRIOR_ROLLING_NUMBER_POSTINGS) / PRIOR_ROLLING_NUMBER_POSTINGS AS PCT_CHANGE_NUMBER_POSTINGS, -- FF.6.2
    COALESCE(CURR_ENROLLMENT.ENROLLMENTS,0) AS CURRENT_NUMBER_ENROLLED, -- FF.7.1
    COALESCE(PRIOR_ENROLLMENT.ENROLLMENTS,0) AS PRIOR_NUMBER_ENROLLED,
    CURRENT_NUMBER_ENROLLED - PRIOR_NUMBER_ENROLLED AS RAW_CHANGE_ENROLLED, -- FF.7.2
    DIV0((CURRENT_NUMBER_ENROLLED - PRIOR_NUMBER_ENROLLED),(PRIOR_NUMBER_ENROLLED)) AS PCT_CHANGE_ENROLLED, -- FF.7.2
    COALESCE(CURR_ASSOC.COMPLETIONS,0) AS CURRENT_ASSOC_COMPLETIONS, -- FF.7.3
    COALESCE(CURR_BACH.COMPLETIONS,0) AS CURRENT_BACH_COMPLETIONS, -- FF.7.3
    COALESCE(CURR_CERTS.COMPLETIONS,0) AS CURRENT_CERT_COMPLETIONS, -- FF.7.3
    COALESCE(CURR_MASTERS.COMPLETIONS,0) AS CURRENT_MASTERS_COMPLETIONS, -- FF.7.3
    COALESCE(CURR_DOCTORS.COMPLETIONS,0) AS CURRENT_DOCTORS_COMPLETIONS, -- FF.7.3
    COALESCE(PRIOR_ASSOC.COMPLETIONS,0) AS PRIOR_ASSOC_COMPLETIONS,
    COALESCE(PRIOR_BACH.COMPLETIONS,0) AS PRIOR_BACH_COMPLETIONS,
    COALESCE(PRIOR_CERTS.COMPLETIONS,0) AS PRIOR_CERT_COMPLETIONS,
    COALESCE(PRIOR_MASTERS.COMPLETIONS,0) AS PRIOR_MASTERS_COMPLETIONS,
    COALESCE(PRIOR_DOCTORS.COMPLETIONS,0) AS PRIOR_DOCTORS_COMPLETIONS,
    CURRENT_ASSOC_COMPLETIONS + CURRENT_BACH_COMPLETIONS + CURRENT_CERT_COMPLETIONS + CURRENT_MASTERS_COMPLETIONS + CURRENT_DOCTORS_COMPLETIONS AS CURRENT_COMPLETIONS, -- FF.7.3
    PRIOR_ASSOC_COMPLETIONS + PRIOR_BACH_COMPLETIONS + PRIOR_CERT_COMPLETIONS + PRIOR_MASTERS_COMPLETIONS + PRIOR_DOCTORS_COMPLETIONS AS PRIOR_COMPLETIONS,
    CURRENT_COMPLETIONS - PRIOR_COMPLETIONS AS RAW_CHANGE_COMPLETIONS, -- FF.7.4
    DIV0(CURRENT_COMPLETIONS - PRIOR_COMPLETIONS, PRIOR_COMPLETIONS) AS PCT_CHANGE_COMPLETIONS, -- FF.7.4
    ACS_DATA.POVERTY_LEVEL_PCT AS POVERTY_LEVEL -- FF.9.1
